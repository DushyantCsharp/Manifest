"""Migrations against a real Postgres (testcontainers): each test gets a throwaway database."""

from collections.abc import Iterator

import pytest
from alembic import command
from alembic.script import ScriptDirectory
from sqlalchemy.exc import DBAPIError

from manifest_db.testing import alembic_config, execute, query, scratch_database

pytestmark = pytest.mark.integration


@pytest.fixture
def database(postgres_url: str) -> Iterator[str]:
    with scratch_database(postgres_url) as url:
        yield url


def current_revision(url: str) -> str | None:
    rows = query(url, "SELECT version_num FROM alembic_version")
    return rows[0][0] if rows else None


def user_tables(url: str) -> set[str]:
    rows = query(url, "SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
    return {row[0] for row in rows} - {"alembic_version"}


def test_upgrade_to_head_and_downgrade_to_base(database: str) -> None:
    config = alembic_config(database)

    command.upgrade(config, "head")
    assert current_revision(database) == "0008"
    assert len(user_tables(database)) == 13

    command.downgrade(config, "base")
    assert current_revision(database) is None
    assert user_tables(database) == set()
    leftovers = query(
        database,
        "SELECT typname FROM pg_type WHERE typtype = 'e' "
        "UNION ALL SELECT extname FROM pg_extension WHERE extname = 'vector'",
    )
    assert leftovers == []

    command.upgrade(config, "head")
    assert current_revision(database) == "0008"


def test_every_step_downgrades_and_reapplies(database: str) -> None:
    """Stairway: each revision can go up, back down one step, and up again."""
    config = alembic_config(database)
    revisions = reversed(list(ScriptDirectory.from_config(config).walk_revisions()))
    for revision in revisions:
        command.upgrade(config, revision.revision)
        command.downgrade(config, str(revision.down_revision or "base"))
        command.upgrade(config, revision.revision)
        assert current_revision(database) == revision.revision


def test_models_match_migrations(database: str) -> None:
    config = alembic_config(database)
    command.upgrade(config, "head")
    command.check(config)  # raises AutogenerateDiffsDetected on any drift


def test_hs_nomenclature_is_searchable(database: str) -> None:
    command.upgrade(alembic_config(database), "head")

    levels = query(database, "SELECT level, count(*) FROM hs_codes GROUP BY level ORDER BY level")
    assert [tuple(row) for row in levels] == [(2, 97), (4, 1229), (6, 5613)]

    matches = query(
        database,
        "SELECT code FROM hs_codes WHERE level = 6 AND search @@ plainto_tsquery('english', :q)",
        q="automatic data processing portable",
    )
    assert "847130" in {row[0] for row in matches}

    [(column_type,)] = query(
        database,
        "SELECT format_type(atttypid, atttypmod) FROM pg_attribute "
        "WHERE attrelid = 'hs_codes'::regclass AND attname = 'embedding'",
    )
    assert column_type == "vector(1024)"


V1_DOCUMENT = """
WITH shipment AS (INSERT INTO shipments DEFAULT VALUES RETURNING id),
document AS (
    INSERT INTO documents (shipment_id, filename, content_type, size_bytes, storage_key)
    SELECT id, 'invoice.pdf', 'application/pdf', 1024, 'raw/invoice.pdf' FROM shipment
    RETURNING id
),
extraction AS (
    INSERT INTO extractions (document_id, schema_version, payload, model, tokens_in, tokens_out)
    SELECT id, 1, '{}'::jsonb, 'test-model', 10, 5 FROM document
    RETURNING id
)
INSERT INTO line_items (extraction_id, line_no, description)
SELECT id, n, 'Widget' FROM extraction, generate_series(1, 2) AS n
"""


def test_contract_waits_for_the_backfill(database: str) -> None:
    config = alembic_config(database)
    command.upgrade(config, "0004")
    execute(database, V1_DOCUMENT)

    with pytest.raises(RuntimeError, match="1 v1 document"):
        command.upgrade(config, "0005")
    assert current_revision(database) == "0004"

    # What re-extraction leaves behind: the v1 extraction superseded by a v2 one.
    execute(database, "UPDATE extractions SET superseded_at = now() WHERE schema_version = 1")
    command.upgrade(config, "0005")
    assert current_revision(database) == "0005"

    [(default,)] = query(
        database,
        "SELECT column_default FROM information_schema.columns "
        "WHERE table_name = 'extractions' AND column_name = 'schema_version'",
    )
    assert default == "2"


def test_v3_contract_waits_for_the_backfill_except_for_failed_documents(database: str) -> None:
    config = alembic_config(database)
    command.upgrade(config, "0007")
    execute(database, V1_DOCUMENT)

    with pytest.raises(RuntimeError, match="1 document"):
        command.upgrade(config, "0008")
    assert current_revision(database) == "0007"

    # A document that failed outright has nothing to re-read: it doesn't hold the contract up.
    execute(database, "UPDATE documents SET status = 'failed'")
    command.upgrade(config, "0008")
    [(default,)] = query(
        database,
        "SELECT column_default FROM information_schema.columns "
        "WHERE table_name = 'extractions' AND column_name = 'schema_version'",
    )
    assert default == "3"
    with pytest.raises(DBAPIError, match="ck_extractions_provenance_since_v3"):
        execute(
            database,
            "INSERT INTO extractions (document_id, payload, model, tokens_in, tokens_out) "
            "SELECT id, '{}'::jsonb, 'm', 1, 1 FROM documents",
        )


@pytest.mark.parametrize(
    ("origin", "rejected_by"),
    [
        ("cn", "ck_line_items_country_of_origin_iso3166"),
        ("C1", "ck_line_items_country_of_origin_iso3166"),
        ("CHN", "value too long for type character"),  # alpha-3 never reaches the check
    ],
)
def test_origin_must_be_iso_3166_alpha_2(database: str, origin: str, rejected_by: str) -> None:
    command.upgrade(alembic_config(database), "head")
    execute(database, V1_DOCUMENT)
    with pytest.raises(DBAPIError, match=rejected_by):
        execute(database, "UPDATE line_items SET country_of_origin = :origin", origin=origin)
    execute(database, "UPDATE line_items SET country_of_origin = 'CN'")
